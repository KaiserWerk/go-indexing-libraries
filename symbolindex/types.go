package symbolindex

import "strings"

// Language identifies the source language for a file or symbol.
type Language string

const (
	LanguageUnknown Language = "unknown"
	LanguageGo      Language = "go"
	LanguageCSharp  Language = "csharp"
)

// SymbolKind is a canonical cross-language kind.
type SymbolKind string

const (
	SymbolKindPackage   SymbolKind = "package"
	SymbolKindNamespace SymbolKind = "namespace"
	SymbolKindType      SymbolKind = "type"
	SymbolKindFunction  SymbolKind = "function"
	SymbolKindMethod    SymbolKind = "method"
	SymbolKindProperty  SymbolKind = "property"
	SymbolKindEvent     SymbolKind = "event"
	SymbolKindIndexer   SymbolKind = "indexer"
	SymbolKindField     SymbolKind = "field"
)

// EdgeType describes a relationship between two symbols.
type EdgeType string

const (
	EdgeTypeContains   EdgeType = "contains"
	EdgeTypeDeclares   EdgeType = "declares"
	EdgeTypeReferences EdgeType = "references"
	EdgeTypeCalls      EdgeType = "calls"
	EdgeTypeInherits   EdgeType = "inherits"
	EdgeTypeImplements EdgeType = "implements"
	EdgeTypeImports    EdgeType = "imports"
)

// DiagnosticLevel classifies diagnostics emitted during indexing.
type DiagnosticLevel string

const (
	DiagnosticLevelError   DiagnosticLevel = "error"
	DiagnosticLevelWarning DiagnosticLevel = "warning"
)

// SourceFile is one caller-provided source unit.
type SourceFile struct {
	Path      string
	Content   string
	Language  Language
	ContextID string
}

// Options controls index behavior.
type Options struct {
	LanguageOverrides map[string]Language
	DefaultContextID  string
	IncludeTests      bool
	IncludeGenerated  bool
}

// Span represents a source location range.
type Span struct {
	Path      string
	LineStart int
	LineEnd   int
}

// Symbol is a canonical symbol record.
type Symbol struct {
	ID                   string
	StableKey            string
	Language             Language
	Kind                 SymbolKind
	LanguageSpecificKind string
	Name                 string
	FQN                  string
	Signature            string
	ContainerFQN         string
	ContextID            string
	Declarations         []Span
}

// Edge connects two symbols with a typed relationship.
type Edge struct {
	Type      EdgeType
	FromID    string
	ToID      string
	ContextID string
}

// Candidate is one possible target for an ambiguous link.
type Candidate struct {
	SymbolID   string
	Confidence float64
}

// Reference captures one symbol usage site.
type Reference struct {
	FromID      string
	ToID        string
	ContextID   string
	Location    Span
	Candidates  []Candidate
	IsAmbiguous bool
}

// Call captures one callable invocation site.
type Call struct {
	CallerID    string
	CalleeID    string
	ContextID   string
	Location    Span
	Candidates  []Candidate
	IsAmbiguous bool
}

// Diagnostic is a non-fatal file or analysis issue.
type Diagnostic struct {
	Level   DiagnosticLevel
	Code    string
	Message string
	Path    string
	Line    int
}

// Result is the storage-agnostic index output.
type Result struct {
	Symbols    []Symbol
	Edges      []Edge
	References []Reference
	Calls      []Call
}

func (o *Options) normalize() {
	if o.DefaultContextID == "" {
		o.DefaultContextID = "default"
	}
	if !o.IncludeTests {
		// false is the desired default
	}
	if !o.IncludeGenerated {
		// false means skip generated files
		return
	}
	// true is the desired default
}

func defaultOptions() Options {
	return Options{
		DefaultContextID: "default",
		IncludeTests:     false,
		IncludeGenerated: true,
	}
}

func isTestPath(path string) bool {
	lower := strings.ToLower(path)
	return strings.HasSuffix(lower, "_test.go") ||
		strings.HasSuffix(lower, "tests.cs") ||
		strings.Contains(lower, "/test/") ||
		strings.Contains(lower, "\\test\\")
}

func isGenerated(path, content string) bool {
	lowerPath := strings.ToLower(path)
	if strings.HasSuffix(lowerPath, ".g.cs") || strings.HasSuffix(lowerPath, ".generated.cs") {
		return true
	}
	header := strings.ToLower(content)
	if len(header) > 400 {
		header = header[:400]
	}
	return strings.Contains(header, "<auto-generated") || strings.Contains(header, "code generated")
}

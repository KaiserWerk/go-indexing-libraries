package astindex

import "strings"

// Language identifies the source language for one file.
type Language string

const (
	LanguageUnknown Language = "unknown"
	LanguageGo      Language = "go"
	LanguageCSharp  Language = "csharp"
)

// NodeKind is a canonical AST node kind across languages.
type NodeKind string

const (
	NodeKindFileRoot         NodeKind = "file_root"
	NodeKindPackage          NodeKind = "package"
	NodeKindNamespace        NodeKind = "namespace"
	NodeKindImport           NodeKind = "import"
	NodeKindUsing            NodeKind = "using"
	NodeKindType             NodeKind = "type"
	NodeKindFunction         NodeKind = "function"
	NodeKindMethod           NodeKind = "method"
	NodeKindField            NodeKind = "field"
	NodeKindProperty         NodeKind = "property"
	NodeKindComment          NodeKind = "comment"
	NodeKindDocComment       NodeKind = "doc_comment"
	NodeKindGenericParameter NodeKind = "generic_parameter"
)

// RelationType describes one edge between two nodes.
type RelationType string

const (
	RelationTypeParent    RelationType = "parent"
	RelationTypeDeclares  RelationType = "declares"
	RelationTypeImports   RelationType = "imports"
	RelationTypeCalls     RelationType = "calls"
	RelationTypeReference RelationType = "references"
)

// DiagnosticLevel classifies diagnostics emitted during parsing.
type DiagnosticLevel string

const (
	DiagnosticLevelError   DiagnosticLevel = "error"
	DiagnosticLevelWarning DiagnosticLevel = "warning"
)

// SourceFile is one caller-provided source unit.
type SourceFile struct {
	Path      string
	Content   string
	Language  Language
	ContextID string
}

// Options controls parser behavior.
type Options struct {
	LanguageOverrides map[string]Language
	DefaultContextID  string
	IncludeTests      bool
	IncludeGenerated  bool
}

// Span represents one source location range.
type Span struct {
	Path      string
	LineStart int
	LineEnd   int
}

// Node is one normalized AST node.
type Node struct {
	ID                   string
	StableKey            string
	Language             Language
	Kind                 NodeKind
	LanguageSpecificKind string
	Name                 string
	FQN                  string
	Signature            string
	ParentID             string
	ContextID            string
	Span                 Span
	LanguageSpecific     map[string]string
}

// Relation connects two nodes.
type Relation struct {
	Type       RelationType
	FromID     string
	ToID       string
	ContextID  string
	Location   Span
	Confidence float64
}

// FileAST is the per-file output unit.
type FileAST struct {
	Path       string
	Language   Language
	ContextID  string
	RootNodeID string
	Nodes      []Node
	Relations  []Relation
}

// Diagnostic is a non-fatal parse or analysis issue.
type Diagnostic struct {
	Level   DiagnosticLevel
	Code    string
	Message string
	Path    string
	Line    int
}

// Result is the storage-agnostic parser output.
type Result struct {
	SchemaVersion string
	Files         []FileAST
}

func defaultOptions() Options {
	return Options{
		DefaultContextID: "default",
		IncludeTests:     false,
		IncludeGenerated: true,
	}
}

func isTestPath(path string) bool {
	lower := strings.ToLower(path)
	return strings.HasSuffix(lower, "_test.go") ||
		strings.HasSuffix(lower, "tests.cs") ||
		strings.Contains(lower, "/test/") ||
		strings.Contains(lower, "\\test\\")
}

func isGenerated(path, content string) bool {
	lowerPath := strings.ToLower(path)
	if strings.HasSuffix(lowerPath, ".g.cs") || strings.HasSuffix(lowerPath, ".generated.cs") {
		return true
	}
	header := strings.ToLower(content)
	if len(header) > 400 {
		header = header[:400]
	}
	return strings.Contains(header, "<auto-generated") || strings.Contains(header, "code generated")
}
